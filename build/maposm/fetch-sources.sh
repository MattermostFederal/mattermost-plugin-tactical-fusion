#!/usr/bin/env bash
set -euo pipefail

BASE="${GEOFABRIK_BASE:-https://download.geofabrik.de}"
HERE="build/maposm"
DEST="${DEST:-$HERE/source}"
LOCK="$HERE/sources.lock"
REGIONS="$HERE/regions.txt"

mkdir -p "$DEST"
rm -f "$DEST"/*.part

sha() { shasum -a 256 "$1" 2>/dev/null | cut -d' ' -f1 || sha256sum "$1" | cut -d' ' -f1; }
md5_of() { md5sum "$1" 2>/dev/null | cut -d' ' -f1 || md5 -q "$1"; }

verify_published_md5() {
    local out="$1" url="$2" want got
    want=$(curl -fsSL --retry 3 "${url}.md5" | awk 'NR == 1 { print tolower($1) }')
    if ! echo "$want" | grep -Eq '^[0-9a-f]{32}$'; then
        echo "error: Geofabrik published no md5 for ${url##*/}" >&2
        return 1
    fi
    got=$(md5_of "$out")
    if [ "$got" != "$want" ]; then
        echo "error: ${url##*/} does not match the md5 Geofabrik publishes beside it" >&2
        echo "  expected $want" >&2
        echo "  got      $got" >&2
        return 1
    fi
}

all_extracts=$(grep -v '^#' "$REGIONS" |
    awk 'NF { n = split($3, a, ","); for (i = 1; i <= n; i++) print a[i] }' |
    sort -u)

collisions=$(printf '%s\n' $all_extracts | sed 's|.*/||' | sort | uniq -d)
if [ -n "$collisions" ]; then
    echo "error: two extracts in $REGIONS share a file name:" >&2
    printf '  %s\n' $collisions >&2
    echo "  $DEST is flat and build.sh looks them up by that name." >&2
    exit 1
fi

extracts=$(grep -v '^#' "$REGIONS" |
    awk -v p="${PROFILE:-}" 'NF {
        if (p != "" && index("," $2 ",", "," p ",") == 0) next
        n = split($3, a, ","); for (i = 1; i <= n; i++) print a[i]
    }' |
    sort -u)

if [ -z "$extracts" ]; then
    echo "error: profile '${PROFILE:-}' selects no region in $REGIONS" >&2
    exit 1
fi

in_scope() {
    for e in $extracts; do
        [ "${e##*/}" = "$1" ] && return 0
    done
    return 1
}

if [ "${UPDATE_LOCK:-}" = "1" ] || [ ! -f "$LOCK" ]; then
    rows=$(mktemp)
    trap 'rm -f "$rows"' EXIT

    if [ -f "$LOCK" ]; then
        while read -r want file stamp; do
            case "$want" in \#*) continue ;; esac
            [ -n "${file:-}" ] || continue
            in_scope "$(echo "$file" | sed 's/-[0-9]\{6\}\.osm\.pbf$//')" && continue
            printf '%s  %s  %s\n' "$want" "$file" "$stamp" >> "$rows"
        done < "$LOCK"
    fi

    for extract in $extracts; do
        if [ -n "${PIN_DATE:-}" ]; then
            file="${extract##*/}-${PIN_DATE}.osm.pbf"
            dated="${BASE}/${extract%/*}/${file}"
        else
            dated=$(curl -fsSLI -o /dev/null -w '%{url_effective}' "${BASE}/${extract}-latest.osm.pbf")
            file=$(basename "$dated")
        fi
        out="$DEST/$file"

        if [ ! -f "$out" ]; then
            echo "fetching ${file}"
            curl -fsSL --retry 3 -o "${out}.part" "$dated"
            mv "${out}.part" "$out"
        fi

        head -c 16 "$out" | grep -qa OSMHeader || {
            echo "error: ${file} is not a PBF; a proxy or portal may have answered" >&2
            exit 1
        }

        verify_published_md5 "$out" "$dated" || { rm -f "$out"; exit 1; }

        stamp=$(curl -fsSLI "$dated" | awk 'tolower($1) == "last-modified:" {$1=""; print}' | tr -d '\r' | sed 's/^ *//')
        echo "$(sha "$out")  ${file}  ${stamp}" >> "$rows"
    done

    : > "$LOCK"
    echo "# Generated by fetch-sources.sh. OpenStreetMap via Geofabrik, ODbL 1.0." >> "$LOCK"
    echo "# sha256  file  extracted" >> "$LOCK"
    sort -k2,2 "$rows" >> "$LOCK"

    for stale in "$DEST"/*.osm.pbf; do
        [ -e "$stale" ] || continue
        awk -v f="${stale##*/}" '!/^#/ && $2 == f { found = 1 } END { exit !found }' "$LOCK" ||
            { echo "removing superseded ${stale##*/}"; rm -f "$stale"; }
    done

    echo "wrote $LOCK"
    exit 0
fi

fail=0
while read -r want file _rest; do
    case "$want" in \#*) continue ;; esac
    [ -n "${file:-}" ] || continue

    out="$DEST/$file"
    region=$(echo "$file" | sed 's/-[0-9]\{6\}\.osm\.pbf$//')

    if [ ! -f "$out" ]; then
        url=$(grep -v '^#' "$REGIONS" | awk -v r="$region" 'NF {
            n = split($3, a, ",")
            for (i = 1; i <= n; i++) {
                leaf = a[i]
                sub(/.*\//, "", leaf)
                if (leaf == r) { print a[i]; exit }
            }
        }')
        [ -n "$url" ] || { echo "error: no region in $REGIONS produces $file" >&2; exit 1; }
        echo "fetching ${file}"
        curl -fsSL --retry 3 -o "${out}.part" "${BASE}/${url%/*}/${file}" || {
            rm -f "${out}.part"
            echo "error: ${file} is gone from Geofabrik, which keeps dailies for about 90 days." >&2
            echo "  Restore it from an internal mirror, or re-pin with UPDATE_LOCK=1." >&2
            exit 1
        }
        mv "${out}.part" "$out"
    fi

    got=$(sha "$out")
    if [ "$got" != "$want" ]; then
        echo "error: $file digest mismatch" >&2
        echo "  expected $want" >&2
        echo "  got      $got" >&2
        fail=1
    fi
done < "$LOCK"

[ "$fail" -eq 0 ] || exit 1
echo "sources verified against $LOCK"
