package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const (
	mercatorLimit  = 85.0511287798066
	pathScale      = 1000000
	adminScale     = 1000000
	simplifyEps    = 0.00025
	geoSimplifyEps = 0.02
	geoDecimals    = 2
)

type geoJSON struct {
	Features []feature `json:"features"`
}

type feature struct {
	Properties map[string]json.RawMessage `json:"properties"`
	Geometry   geometry                   `json:"geometry"`
}

type geometry struct {
	Type        string          `json:"type"`
	Coordinates json.RawMessage `json:"coordinates"`
}

type point struct{ X, Y float64 }

func main() {
	src := flag.String("source", "build/mapdata/source", "directory holding Natural Earth GeoJSON")
	out := flag.String("out", "server/decorators/location/mapdata", "package directory to write")
	geo := flag.String("geo", "public/map/world.geo.json", "browser basemap to write")
	digest := flag.String("digest", "webapp/src/decorators/location/map/basemap_digest.ts", "generated digest module")
	flag.Parse()

	landGeo, err := readPolygonRings(filepath.Join(*src, "ne_110m_land.geojson"))
	fail(err)
	lakesGeo, err := readPolygonRings(filepath.Join(*src, "ne_110m_lakes.geojson"))
	fail(err)
	bordersGeo, err := readLineStrings(filepath.Join(*src, "ne_110m_admin_0_boundary_lines_land.geojson"))
	fail(err)
	countries, err := readCountries(filepath.Join(*src, "ne_110m_admin_0_countries.geojson"))
	fail(err)

	fail(os.MkdirAll(*out, 0o755))
	fail(writeAdmin(filepath.Join(*out, "admin.go"), countries))

	fail(os.MkdirAll(filepath.Dir(*geo), 0o755))
	basemap := buildBasemap(landGeo, lakesGeo, bordersGeo)
	fail(os.WriteFile(*geo, basemap, 0o644))

	sum := sha256.Sum256(basemap)
	fail(os.MkdirAll(filepath.Dir(*digest), 0o755))
	fail(writeDigest(*digest, hex.EncodeToString(sum[:])))
}

func buildBasemap(land, lakes, borders [][]point) []byte {
	var b bytes.Buffer
	b.WriteString(`{"type":"FeatureCollection","features":[`)
	first := true
	writeFeature := func(layer, geomType string, rings [][]point) {
		for _, ring := range rings {
			if len(ring) < 2 {
				continue
			}
			if !first {
				b.WriteByte(',')
			}
			first = false
			b.WriteString(`{"type":"Feature","properties":{"layer":"`)
			b.WriteString(layer)
			b.WriteString(`"},"geometry":{"type":"`)
			b.WriteString(geomType)
			b.WriteString(`","coordinates":`)
			if geomType == "Polygon" {
				b.WriteByte('[')
			}
			writeCoordinates(&b, ring)
			if geomType == "Polygon" {
				b.WriteByte(']')
			}
			b.WriteString(`}}`)
		}
	}
	writeFeature("land", "Polygon", land)
	writeFeature("lakes", "Polygon", lakes)
	writeFeature("borders", "LineString", borders)
	b.WriteString(`]}`)
	return b.Bytes()
}

func writeCoordinates(b *bytes.Buffer, ring []point) {
	b.WriteByte('[')
	for i, p := range ring {
		if i > 0 {
			b.WriteByte(',')
		}
		b.WriteByte('[')
		b.WriteString(strconv.FormatFloat(p.X, 'f', -1, 64))
		b.WriteByte(',')
		b.WriteString(strconv.FormatFloat(p.Y, 'f', -1, 64))
		b.WriteByte(']')
	}
	b.WriteByte(']')
}

func writeDigest(path, sum string) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by build/mapdata. DO NOT EDIT.\n\n")
	b.WriteString("export const BASEMAP_SHA256 = '" + sum + "';\n")
	return os.WriteFile(path, b.Bytes(), 0o644)
}

func fail(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "mapdata:", err)
		os.Exit(1)
	}
}

func readGeoJSON(path string) (*geoJSON, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var g geoJSON
	if err := json.Unmarshal(raw, &g); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(g.Features) == 0 {
		return nil, fmt.Errorf("%s: no features", path)
	}
	return &g, nil
}

func readPolygonRings(path string) ([][]point, error) {
	g, err := readGeoJSON(path)
	if err != nil {
		return nil, err
	}
	var geo [][]point
	for _, f := range g.Features {
		polys, err := decodePolygons(f.Geometry)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		for _, poly := range polys {
			for _, ring := range poly {
				geo = append(geo, degreeRing(ring))
			}
		}
	}
	return geo, nil
}

func readLineStrings(path string) ([][]point, error) {
	g, err := readGeoJSON(path)
	if err != nil {
		return nil, err
	}
	var geo [][]point
	add := func(ring [][2]float64) {
		geo = append(geo, degreeRing(ring))
	}
	for _, f := range g.Features {
		switch f.Geometry.Type {
		case "LineString":
			var ring [][2]float64
			if err := json.Unmarshal(f.Geometry.Coordinates, &ring); err != nil {
				return nil, fmt.Errorf("%s: %w", path, err)
			}
			add(ring)
		case "MultiLineString":
			var multi [][][2]float64
			if err := json.Unmarshal(f.Geometry.Coordinates, &multi); err != nil {
				return nil, fmt.Errorf("%s: %w", path, err)
			}
			for _, ring := range multi {
				add(ring)
			}
		default:
			return nil, fmt.Errorf("%s: unexpected geometry %q", path, f.Geometry.Type)
		}
	}
	return geo, nil
}

func degreeRing(ring [][2]float64) []point {
	pts := make([]point, 0, len(ring))
	for _, c := range ring {
		pts = append(pts, point{X: roundDec(c[0], geoDecimals), Y: roundDec(c[1], geoDecimals)})
	}
	return dedupe(simplify(pts, geoSimplifyEps))
}

func roundDec(v float64, places int) float64 {
	f := math.Pow(10, float64(places))
	r := math.Round(v*f) / f
	if r == 0 {
		return 0
	}
	return r
}

func dedupe(pts []point) []point {
	out := pts[:0:0]
	for i, p := range pts {
		if i > 0 && p == pts[i-1] {
			continue
		}
		out = append(out, p)
	}
	return out
}

func decodePolygons(g geometry) ([][][][2]float64, error) {
	switch g.Type {
	case "Polygon":
		var poly [][][2]float64
		if err := json.Unmarshal(g.Coordinates, &poly); err != nil {
			return nil, err
		}
		return [][][][2]float64{poly}, nil
	case "MultiPolygon":
		var multi [][][][2]float64
		if err := json.Unmarshal(g.Coordinates, &multi); err != nil {
			return nil, err
		}
		return multi, nil
	default:
		return nil, fmt.Errorf("unexpected geometry %q", g.Type)
	}
}

func project(lon, lat float64) point {
	lat = math.Max(-mercatorLimit, math.Min(mercatorLimit, lat))
	rad := lat * math.Pi / 180
	y := (1 - math.Log(math.Tan(rad)+1/math.Cos(rad))/math.Pi) / 2
	return point{X: (lon + 180) / 360, Y: y}
}

func simplify(pts []point, eps float64) []point {
	if len(pts) < 3 {
		return pts
	}
	keep := make([]bool, len(pts))
	keep[0] = true
	keep[len(pts)-1] = true
	douglasPeucker(pts, 0, len(pts)-1, eps, keep)

	out := make([]point, 0, len(pts))
	for i, k := range keep {
		if k {
			out = append(out, pts[i])
		}
	}
	return out
}

func douglasPeucker(pts []point, first, last int, eps float64, keep []bool) {
	if last <= first+1 {
		return
	}
	worst, index := 0.0, first
	for i := first + 1; i < last; i++ {
		if d := perpendicular(pts[i], pts[first], pts[last]); d > worst {
			worst, index = d, i
		}
	}
	if worst <= eps {
		return
	}
	keep[index] = true
	douglasPeucker(pts, first, index, eps, keep)
	douglasPeucker(pts, index, last, eps, keep)
}

func perpendicular(p, a, b point) float64 {
	dx, dy := b.X-a.X, b.Y-a.Y
	if dx == 0 && dy == 0 {
		return math.Hypot(p.X-a.X, p.Y-a.Y)
	}
	t := ((p.X-a.X)*dx + (p.Y-a.Y)*dy) / (dx*dx + dy*dy)
	t = math.Max(0, math.Min(1, t))
	return math.Hypot(p.X-(a.X+t*dx), p.Y-(a.Y+t*dy))
}

type country struct {
	Name  string
	Polys [][][]([2]float64)
}

func readCountries(path string) ([]country, error) {
	g, err := readGeoJSON(path)
	if err != nil {
		return nil, err
	}
	out := make([]country, 0, len(g.Features))
	for _, f := range g.Features {
		raw, ok := f.Properties["ADMIN"]
		if !ok {
			return nil, fmt.Errorf("%s: feature without an ADMIN field", path)
		}
		var name string
		if err := json.Unmarshal(raw, &name); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if strings.TrimSpace(name) == "" {
			return nil, fmt.Errorf("%s: empty ADMIN field", path)
		}
		// The admin table is encoded as "name|geometry", one country per line,
		// so a name carrying either delimiter would silently truncate or split a
		// country rather than fail.
		if strings.ContainsAny(name, "|\n") {
			return nil, fmt.Errorf("%s: ADMIN %q contains an encoding delimiter", path, name)
		}
		polys, err := decodePolygons(f.Geometry)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		out = append(out, country{Name: name, Polys: polys})
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func writeFormatted(path string, src []byte) error {
	pretty, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}

	return os.WriteFile(path, pretty, 0o644)
}

func writeAdmin(path string, countries []country) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by build/mapdata. DO NOT EDIT.\n\npackage mapdata\n\n")
	b.WriteString("var Countries = decodeCountries(\"")

	var enc strings.Builder
	for i, c := range countries {
		if i > 0 {
			enc.WriteByte('\n')
		}
		enc.WriteString(c.Name)
		enc.WriteByte('|')
		for pi, poly := range c.Polys {
			if pi > 0 {
				enc.WriteByte(';')
			}
			for ri, ring := range poly {
				if ri > 0 {
					enc.WriteByte(':')
				}
				enc.WriteString(encodeRing(ring))
			}
		}
	}
	b.WriteString(strings.TrimPrefix(strconv.Quote(enc.String()), "\""))
	b.WriteString(")\n")
	return writeFormatted(path, b.Bytes())
}

func encodeRing(ring [][2]float64) string {
	var sb strings.Builder
	var px, py int64
	for i, c := range ring {
		x := int64(math.Round(c[0] * adminScale))
		y := int64(math.Round(c[1] * adminScale))
		if i > 0 {
			sb.WriteByte(',')
		}
		sb.WriteString(strconv.FormatInt(x-px, 36))
		sb.WriteByte(' ')
		sb.WriteString(strconv.FormatInt(y-py, 36))
		px, py = x, y
	}
	return sb.String()
}
