package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const adminScale = 1000000

type geoJSON struct {
	Features []feature `json:"features"`
}

type feature struct {
	Properties map[string]json.RawMessage `json:"properties"`
	Geometry   geometry                   `json:"geometry"`
}

type geometry struct {
	Type        string          `json:"type"`
	Coordinates json.RawMessage `json:"coordinates"`
}

func main() {
	src := flag.String("source", "build/mapdata/source", "directory holding Natural Earth GeoJSON")
	out := flag.String("out", "server/decorators/location/mapdata", "package directory to write")
	flag.Parse()

	countries, err := readCountries(filepath.Join(*src, "ne_110m_admin_0_countries.geojson"))
	fail(err)

	fail(os.MkdirAll(*out, 0o755))
	fail(writeAdmin(filepath.Join(*out, "admin.go"), countries))
}

func fail(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "mapdata:", err)
		os.Exit(1)
	}
}

func readGeoJSON(path string) (*geoJSON, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var g geoJSON
	if err := json.Unmarshal(raw, &g); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(g.Features) == 0 {
		return nil, fmt.Errorf("%s: no features", path)
	}
	return &g, nil
}

func decodePolygons(g geometry) ([][][][2]float64, error) {
	switch g.Type {
	case "Polygon":
		var poly [][][2]float64
		if err := json.Unmarshal(g.Coordinates, &poly); err != nil {
			return nil, err
		}
		return [][][][2]float64{poly}, nil
	case "MultiPolygon":
		var multi [][][][2]float64
		if err := json.Unmarshal(g.Coordinates, &multi); err != nil {
			return nil, err
		}
		return multi, nil
	default:
		return nil, fmt.Errorf("unexpected geometry %q", g.Type)
	}
}

type country struct {
	Name  string
	Polys [][][]([2]float64)
}

func readCountries(path string) ([]country, error) {
	g, err := readGeoJSON(path)
	if err != nil {
		return nil, err
	}
	out := make([]country, 0, len(g.Features))
	for _, f := range g.Features {
		raw, ok := f.Properties["ADMIN"]
		if !ok {
			return nil, fmt.Errorf("%s: feature without an ADMIN field", path)
		}
		var name string
		if err := json.Unmarshal(raw, &name); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if strings.TrimSpace(name) == "" {
			return nil, fmt.Errorf("%s: empty ADMIN field", path)
		}
		// The admin table is encoded as "name|geometry", one country per line,
		// so a name carrying either delimiter would silently truncate or split a
		// country rather than fail.
		if strings.ContainsAny(name, "|\n") {
			return nil, fmt.Errorf("%s: ADMIN %q contains an encoding delimiter", path, name)
		}
		polys, err := decodePolygons(f.Geometry)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		out = append(out, country{Name: name, Polys: polys})
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func writeFormatted(path string, src []byte) error {
	pretty, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}

	return os.WriteFile(path, pretty, 0o644)
}

func writeAdmin(path string, countries []country) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by build/mapdata. DO NOT EDIT.\n\npackage mapdata\n\n")
	b.WriteString("var Countries = decodeCountries(\"")

	var enc strings.Builder
	for i, c := range countries {
		if i > 0 {
			enc.WriteByte('\n')
		}
		enc.WriteString(c.Name)
		enc.WriteByte('|')
		for pi, poly := range c.Polys {
			if pi > 0 {
				enc.WriteByte(';')
			}
			for ri, ring := range poly {
				if ri > 0 {
					enc.WriteByte(':')
				}
				enc.WriteString(encodeRing(ring))
			}
		}
	}
	b.WriteString(strings.TrimPrefix(strconv.Quote(enc.String()), "\""))
	b.WriteString(")\n")
	return writeFormatted(path, b.Bytes())
}

func encodeRing(ring [][2]float64) string {
	var sb strings.Builder
	var px, py int64
	for i, c := range ring {
		x := int64(math.Round(c[0] * adminScale))
		y := int64(math.Round(c[1] * adminScale))
		if i > 0 {
			sb.WriteByte(',')
		}
		sb.WriteString(strconv.FormatInt(x-px, 36))
		sb.WriteByte(' ')
		sb.WriteString(strconv.FormatInt(y-py, 36))
		px, py = x, y
	}
	return sb.String()
}
