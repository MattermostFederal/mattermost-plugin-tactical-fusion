#!/usr/bin/env bash
set -euo pipefail

NE_TAG="${NE_TAG:-v5.1.2}"
BASE="https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${NE_TAG}/geojson"
HERE="build/maptiles"
DEST="${DEST:-$HERE/source}"
LOCK="$HERE/sources.lock"

mkdir -p "$DEST"

sha() { shasum -a 256 "$1" 2>/dev/null | cut -d' ' -f1 || sha256sum "$1" | cut -d' ' -f1; }

files=$(grep -v '^#' "$HERE/sources.txt" | awk 'NF {print $2}')

for name in $files; do
    out="$DEST/${name}.geojson"
    if [ ! -f "$out" ]; then
        echo "fetching ${name}"
        curl -fsSL --retry 3 -o "$out" "${BASE}/${name}.geojson"
    fi
    head -c 1 "$out" | grep -q '{' || {
        echo "error: ${name} is not JSON; a proxy or portal may have answered" >&2
        exit 1
    }
done

if [ "${UPDATE_LOCK:-}" = "1" ] || [ ! -f "$LOCK" ]; then
    : > "$LOCK"
    {
        echo "# Generated by fetch-sources.sh. Natural Earth tag ${NE_TAG}."
        for name in $files; do
            echo "$(sha "$DEST/${name}.geojson")  ${name}.geojson"
        done
    } > "$LOCK"
    echo "wrote $LOCK"
    exit 0
fi

fail=0
while read -r want file; do
    case "$want" in \#*) continue ;; esac
    [ -n "${file:-}" ] || continue
    got=$(sha "$DEST/$file")
    if [ "$got" != "$want" ]; then
        echo "error: $file digest mismatch" >&2
        echo "  expected $want" >&2
        echo "  got      $got" >&2
        fail=1
    fi
done < "$LOCK"

[ "$fail" -eq 0 ] || exit 1
echo "sources verified against $LOCK"
